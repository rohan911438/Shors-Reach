/**
 * Bundles server/attest.ts → api/attest.js (single ESM file, all deps inlined).
 * Why: @cosmjs/crypto is CommonJS and require()s the ESM-only @noble/hashes v2; Vercel's function loader
 * rejects that (ERR_REQUIRE_ESM). Bundling resolves it at build time. Run after changing server/attest.ts:
 *   node scripts/build-api.mjs
 */
import { build } from "esbuild";

await build({
  entryPoints: ["server/attest.ts"],
  outfile: "api/attest.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: false,
  legalComments: "none",
  banner: {
    js: [
      "// GENERATED by scripts/build-api.mjs from server/attest.ts — do not edit by hand.",
      'import { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);',
    ].join("\n"),
  },
  logLevel: "info",
});
